#!/usr/bin/env python3
"""Generate the demo seed SQL for the LabTether hub.

Usage:
    python3 scripts/generate-demo-seed.py > scripts/demo-seed.sql

Standard library only. The data lives in scripts/demo_seed/. Every time in the
output is relative to the moment the file is loaded (NOW() - INTERVAL ...), so
the file never goes stale and running this twice gives the same bytes.
"""

import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))

from demo_seed import alerts, audit, fleet, incidents, logs, operations, telemetry, topology  # noqa: E402
from demo_seed.sqlgen import header  # noqa: E402

# Every table the seed fills, children before parents. CASCADE also clears the
# rows the hub keeps about these devices (heartbeats, presence, derived
# records); the hub writes them again on its next pass.
TRUNCATE = [
    "zone_members", "topology_connections", "topology_zones", "topology_layouts", "asset_edges",
    "metric_samples", "notification_history", "notification_channels", "alert_silences",
    "alert_instances", "alert_rules", "incident_assets", "incident_events", "incident_alert_links",
    "incidents", "log_events", "audit_events", "action_runs", "saved_actions", "scheduled_tasks",
    "webhooks", "update_runs", "update_plans", "group_maintenance_windows", "groups", "assets",
]


def check() -> None:
    """Stop before writing anything if a row names a device or group that does not exist."""
    fleet.check_fleet()
    topology.check_topology()
    telemetry.check_telemetry()
    logs.check_logs()
    alerts.check_alerts()
    incidents.check_incidents()
    operations.check_operations()
    audit.check_audit()


def truncate_sql() -> str:
    lines = []
    for start in range(0, len(TRUNCATE), 5):
        lines.append("    " + ", ".join(TRUNCATE[start:start + 5]))
    return header("TRUNCATE") + "TRUNCATE\n" + ",\n".join(lines) + "\nCASCADE;\n\n"


def main() -> None:
    check()
    out = sys.stdout
    out.write("-- LabTether demo seed data\n")
    out.write("-- Generated by scripts/generate-demo-seed.py. Do not edit by hand.\n")
    out.write("-- Safe to load again: it empties the demo tables first.\n")
    out.write("-- Every time is relative to the load, so the data is always current.\n\n")
    out.write("BEGIN;\n\n")
    out.write(truncate_sql())
    for part in (
        audit.demo_user_sql(),
        fleet.groups_sql(),
        fleet.assets_sql(),
        topology.topology_sql(),
        alerts.alerts_sql(),
        incidents.incidents_sql(),
        telemetry.metrics_sql(),
        logs.logs_sql(),
        operations.operations_sql(),
        audit.audit_sql(),
    ):
        out.write(part)
        if not part.endswith("\n\n"):
            out.write("\n")
    out.write("COMMIT;\n")
    sys.stderr.write(
        f"Generated: {len(fleet.GROUPS)} groups, {len(fleet.HOSTS)} hosts, {len(topology.edges())} links, "
        f"{len(alerts.RULES)} alert rules, {len(alerts.INSTANCES)} alerts, {len(incidents.INCIDENTS)} issues, "
        f"{len(telemetry.profiles())} metric series, {len(logs.log_events())} log lines, "
        f"{len(operations.SAVED_ACTIONS)} saved actions, {len(operations.ACTION_RUNS)} action runs, "
        f"{len(operations.SCHEDULES)} schedules, {len(operations.WEBHOOKS)} webhooks, "
        f"{len(operations.UPDATE_PLANS)} update plans, {len(operations.UPDATE_RUNS)} update runs, "
        f"{len(audit.EVENTS)} audit events\n"
    )


if __name__ == "__main__":
    main()
